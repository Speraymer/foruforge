const C = (value, benefit, cost) => [value, benefit, cost]
const Q = (id, path, title, level, options, impact, defaultValue = '暂停并确认') => ({ id, group:paths[path], category:paths[path].split('/')[0], title, level, options:options.map(x=>x[0]), optionDetails:Object.fromEntries(options.map(x=>[x[0],{benefit:x[1],cost:x[2]}])), impact, defaultValue, noteIds:[] })

